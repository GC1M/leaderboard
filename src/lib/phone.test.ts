import { normalizePhone } from './phone';

test.each([
  ['(555) 555-0100', '+15555550100'],
  ['(415) 212-7777', '+14152127777'],
  ['415-212-7777', '+14152127777'],
  ['1 415 212 7777', '+14152127777'],
  ['+1 415.212.7777', '+14152127777'],
  ['+44 20 7946 0958', '+442079460958'],
  ['+44 (0) 7911 123456', '+447911123456'],
  ['+44 07911 123456', '+447911123456'],
  ['+39 06 1234 5678', '+390612345678'],
])('normalizes %s', (input, expected) => {
  expect(normalizePhone(input)).toBe(expected);
});

test.each(['', 'abc', '12345', '+123', '0152127777', '+0 415 212 7777', '+1 (055) 555-0100', '(0) 20 7946 0958', '+12345678', '415 212 7777 99', 'a@b.co'])(
  'rejects %s',
  (input) => {
    expect(normalizePhone(input)).toBeNull();
  },
);
